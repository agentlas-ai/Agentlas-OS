def _readiness(restored: bool = False) -> dict[str, Any]:
    if restored:
        code = "contract_parity_not_proven"
        message = "Selected original contracts were restored, but package references, runtime permissions and equivalent experiment conditions still require host verification."
    else:
        code = "contract_metadata_not_restored"
        message = "Agentlas contract metadata was not copied. Restore or regenerate it through an authorized workflow and validate its references and permissions before execution or experiments."
    return {"readiness": "host_execution_unverified", "blockers": [{"code": code, "message": message}]}


class BuildWorkspaceError(ValueError):
    """A machine-readable refusal; the code is safe to display without file contents."""

    def __init__(self, code: str):
        self.code = code
        super().__init__(code)


def _absolute(value: str | os.PathLike[str]) -> Path:
    if not isinstance(value, (str, os.PathLike)) or not os.fspath(value):
        raise BuildWorkspaceError("invalid_path")
    return Path(os.path.abspath(os.path.expanduser(os.fspath(value))))


def _key(path: Path) -> tuple[str, ...]:
    return tuple(unicodedata.normalize("NFC", part).casefold() for part in path.parts)


def _overlap(a: Path, b: Path) -> bool:
    left, right = _key(a), _key(b)
    return left[:len(right)] == right or right[:len(left)] == left


def _open_dir(path: Path) -> Any:
    try:
        if paths._secure_dir_fd_available():
            return paths._open_absolute_directory(path)
        if os.name != "nt":
            raise BuildWorkspaceError("workspace_secure_snapshot_unavailable")
        return paths._open_absolute_path_directory(path)
    except (OSError, paths.PackageAdaptationError) as exc:
        raise BuildWorkspaceError("unsafe_directory") from exc


def _identity(meta: os.stat_result) -> tuple[int, ...]:
    return (meta.st_dev, meta.st_ino, meta.st_size, meta.st_mtime_ns, meta.st_ctime_ns, meta.st_mode, meta.st_nlink)


def _read_file(directory: Any, name: str, limit: int = revisions.MAX_FILE_BYTES, *, input_budget: list[int] | None = None) -> bytes:
    descriptor = None
    try:
        before = paths._dir_entry_lstat(directory, name)
        if paths._is_link_like(before) or not stat.S_ISREG(before.st_mode) or before.st_nlink != 1:
            raise BuildWorkspaceError("unsafe_asset")
        if before.st_size > limit:
            raise BuildWorkspaceError("asset_too_large")
        if input_budget is not None and before.st_size > input_budget[0]:
            raise BuildWorkspaceError("workspace_input_byte_limit")
        flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_NONBLOCK", 0) | getattr(os, "O_BINARY", 0)
        if isinstance(directory, paths._PathDir):
            directory.verify()
            descriptor = os.open(directory.path / name, flags)
        else:
            descriptor = os.open(name, flags, dir_fd=directory)
        opened = os.fstat(descriptor)
        if _identity(opened) != _identity(before):
            raise BuildWorkspaceError("asset_changed")
        pieces: list[bytes] = []
        # The input-budget path never reads past the already budgeted stat size;
        # a growing or replaced file is rejected by the post-read identity check.
        remaining = before.st_size if input_budget is not None else limit + 1
        while remaining:
            piece = os.read(descriptor, min(64 * 1024, remaining))
            if not piece:
                break
            pieces.append(piece)
            remaining -= len(piece)
        body = b"".join(pieces)
        if isinstance(directory, paths._PathDir):
            directory.verify()
        after = paths._dir_entry_lstat(directory, name)
        if _identity(before) != _identity(os.fstat(descriptor)) or _identity(before) != _identity(after) or len(body) != before.st_size:
            raise BuildWorkspaceError("asset_changed")
        if input_budget is not None:
            input_budget[0] -= len(body)
        return body
    except (OSError, paths.PackageAdaptationError) as exc:
        raise BuildWorkspaceError("asset_changed_or_unreadable") from exc
    finally:
        if descriptor is not None:
            os.close(descriptor)


def _excluded(relative: str, directory: bool) -> bool:
    parts = relative.split("/")
    name = parts[-1].lower()
    if any(part.lower() in _PRIVATE_DIRS for part in parts) or name in _PRIVATE_NAMES:
        return True
    if _PRIVATE_SUFFIX.search(name) or _PRIVATE_NAME.search(name):
        return True
    try:
        revisions.asset_path(relative)
    except revisions.RevisionError as exc:
        if str(exc) == "private_asset_excluded":
            return True
        raise BuildWorkspaceError("invalid_asset_path") from exc
    return False


def _check_structured_secrets(text: str, relative: str) -> None:
    """Reject populated credential fields in JSON as well as text patterns.

    This is a limited local-copy guard, not proof that text or binary assets
    contain no secrets. Inspect object pairs before collapsing duplicate keys.
    """
    suffix = Path(relative).suffix.lower()
    if suffix not in {".json", ".jsonl"}:
        return

    def pairs_hook(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
        for key, value in pairs:
            normalized = re.sub(r"[^a-z0-9]", "", key.lower())
            if normalized in _SENSITIVE_JSON_KEYS and isinstance(value, str):
                candidate = value.strip()
                if candidate and not _SECRET_PLACEHOLDER.fullmatch(candidate):
                    raise BuildWorkspaceError("secret_like_asset")
        return dict(pairs)

    texts = text.splitlines() if suffix == ".jsonl" else (text,)
    for item in texts:
        if not item.strip():
            continue
        try:
            json.loads(item, object_pairs_hook=pairs_hook)
        except (json.JSONDecodeError, RecursionError):
            # Other syntaxes are still subject to the text-pattern checks.
            continue


def _contract_hashes(root: Any, *, input_budget: list[int] | None = None) -> dict[str, str | None]:
    result: dict[str, str | None] = {name: None for name in _CONTRACT_FILES}
    try:
        try:
            info = paths._dir_entry_lstat(root, ".agentlas")
        except FileNotFoundError:
            return result
        if paths._is_link_like(info) or not stat.S_ISDIR(info.st_mode):
            raise BuildWorkspaceError("unsafe_contract_directory")
        directory = paths._open_directory_at(root, ".agentlas")
        try:
            for name in _CONTRACT_FILES:
                try:
                    result[name] = revisions.digest_bytes(_read_file(directory, name, input_budget=input_budget))
                except FileNotFoundError:
                    pass
                except BuildWorkspaceError as exc:
                    if isinstance(exc.__cause__, FileNotFoundError):
                        continue
                    raise
        finally:
            paths._dir_close(directory)
        return result
    except (OSError, paths.PackageAdaptationError) as exc:
        raise BuildWorkspaceError("contract_metadata_unreadable") from exc


def _scan(root: Path, *, input_budget: list[int] | None = None) -> tuple[dict[str, Any], dict[str, bytes]]:
    directory = _open_dir(root)
    root_stat = os.lstat(directory.path) if isinstance(directory, paths._PathDir) else os.fstat(directory)
    root_identity = [root_stat.st_dev, root_stat.st_ino]
    rows: list[dict[str, Any]] = []
    directories: list[str] = []
    omitted: list[str] = []
    unscanned_binary: list[str] = []
    blobs: dict[str, bytes] = {}
    names_seen: set[str] = set()
    total = 0

    def walk(current: Any, prefix: str = "") -> None:
        nonlocal total
        try:
            with paths._dir_scandir(current) as entries:
                names = sorted((entry.name for entry in entries), key=lambda value: value.encode("utf-8"))
            for name in names:
                relative = f"{prefix}/{name}" if prefix else name
                info = paths._dir_entry_lstat(current, name)
                if paths._is_link_like(info):
                    raise BuildWorkspaceError("unsafe_asset_link")
                is_dir = stat.S_ISDIR(info.st_mode)
                if _excluded(relative, is_dir):
                    omitted.append(relative)
                    if len(omitted) + len(names_seen) > revisions.MAX_FILES * 2:
                        raise BuildWorkspaceError("tree_entry_limit")
                    continue
                collision = unicodedata.normalize("NFC", relative).casefold()
                if collision in names_seen:
                    raise BuildWorkspaceError("asset_path_collision")
                names_seen.add(collision)
                if len(names_seen) > revisions.MAX_FILES * 2:
                    raise BuildWorkspaceError("tree_entry_limit")
                if is_dir:
                    directories.append(relative)
                    child = paths._open_directory_at(current, name)
                    try:
                        walk(child, relative)
                    finally:
                        paths._dir_close(child)
                    continue
                if not stat.S_ISREG(info.st_mode):
                    raise BuildWorkspaceError("unsafe_asset")
                body = _read_file(current, name, input_budget=input_budget)
                if _identity(info) != _identity(paths._dir_entry_lstat(current, name)):
                    raise BuildWorkspaceError("asset_changed")
                if body.startswith(b"SQLite format 3\x00") or body[:4] in (b"\x37\x7f\x06\x82", b"\x37\x7f\x06\x83"):
                    omitted.append(relative)
                    continue
                try:
                    text = body.decode("utf-8")
                    if "\x00" in text:
                        unscanned_binary.append(relative)
                except UnicodeDecodeError:
                    text = ""
                    unscanned_binary.append(relative)
                if text and secret_like_kinds(text):
                    raise BuildWorkspaceError("secret_like_asset")
                if text:
                    _check_structured_secrets(text, relative)
                total += len(body)
                if len(rows) >= revisions.MAX_FILES or total > revisions.MAX_TREE_BYTES:
                    raise BuildWorkspaceError("tree_byte_or_count_limit")
                digest = revisions.digest_bytes(body)
                blobs[digest] = body
                rows.append({"path": relative, "blobHash": digest, "byteLength": len(body), "executable": bool(info.st_mode & 0o111)})
        except (OSError, paths.PackageAdaptationError) as exc:
            raise BuildWorkspaceError("asset_changed_or_unreadable") from exc

    try:
        walk(directory)
        contracts = _contract_hashes(directory, input_budget=input_budget)
        current_root = _open_dir(root)
        try:
            current_stat = os.lstat(current_root.path) if isinstance(current_root, paths._PathDir) else os.fstat(current_root)
            if [current_stat.st_dev, current_stat.st_ino] != root_identity:
                raise BuildWorkspaceError("asset_changed")
        finally:
            paths._dir_close(current_root)
    finally:
        paths._dir_close(directory)

    # Resolve the canonical entry from already captured bytes, never a second
    # unrestricted walk of the source directory.
    root_names = {row["path"].lower(): row for row in rows if "/" not in row["path"]}
    canonical = None
    manifest = root_names.get("agentlas.json")
    if manifest:
        try:
            parsed = json.loads(blobs[manifest["blobHash"]].decode("utf-8"))
            if not isinstance(parsed, dict):
                raise ValueError
            canonical = parsed.get("entry")
            if canonical is not None:
                revisions.asset_path(canonical)
                entry = next(row for row in rows if row["path"] == canonical)
                blobs[entry["blobHash"]].decode("utf-8")
        except (ValueError, TypeError, StopIteration, revisions.RevisionError) as exc:
            raise BuildWorkspaceError("invalid_canonical_entry") from exc
    if canonical is None:
        for name in ("system-prompt.md", "soul.md", "agent.md", "claude.md", "agents.md", "gemini.md", "persona.md", "prompt.md"):
            if name in root_names:
                canonical = root_names[name]["path"]
                try:
                    blobs[root_names[name]["blobHash"]].decode("utf-8")
                except UnicodeDecodeError as exc:
                    raise BuildWorkspaceError("invalid_canonical_entry") from exc
                break
    for row in rows:
        row["role"] = revisions.asset_role(row["path"], canonical)
    try:
        tree = revisions.tree_payload(rows)
        digest = revisions.tree_digest(tree["files"])
    except revisions.RevisionError as exc:
        raise BuildWorkspaceError("invalid_revision_tree") from exc
    stable = {"treeDigest": digest, "canonicalEntry": canonical, "directories": sorted(directories), "contractMetadata": contracts, "rootIdentity": root_identity}
    fingerprint = revisions.digest_bytes(revisions.canonical_json(stable).encode("utf-8"))
    return {**tree, **stable, "digest": fingerprint, "omittedPaths": sorted(omitted), "unscannedBinaryPaths": sorted(unscanned_binary)}, blobs


def _collisions(inventories: Sequence[Mapping[str, Any]]) -> list[dict[str, Any]]:
    grouped: dict[str, list[dict[str, Any]]] = {}
    for index, inventory in enumerate(inventories):
        for name in inventory["directories"]:
            grouped.setdefault(unicodedata.normalize("NFC", name).casefold(), []).append({"input": index, "path": name, "kind": "directory"})
        for row in inventory["files"]:
            grouped.setdefault(unicodedata.normalize("NFC", row["path"]).casefold(), []).append({"input": index, "path": row["path"], "kind": "file", "blobHash": row["blobHash"], "executable": row["executable"]})
    conflicts = []
    for key, items in sorted(grouped.items()):
        if len({item["input"] for item in items}) < 2 or all(item["kind"] == "directory" for item in items):
            continue
        if any(item["kind"] == "directory" for item in items):
            kind = "file_directory"
        elif len({(item["blobHash"], item["executable"]) for item in items}) == 1:
            kind = "identical"
        else:
            kind = "different"
        conflicts.append({"normalizedPath": key, "kind": kind, "entries": items})
    return conflicts


def _make_dir(parent: Any, name: str) -> Any:
    try:
        if isinstance(parent, paths._PathDir):
            parent.verify()
            os.mkdir(parent.path / name, 0o700)
        else:
            os.mkdir(name, 0o700, dir_fd=parent)
        return paths._open_directory_at(parent, name)
    except FileExistsError as exc:
        raise BuildWorkspaceError("output_exists") from exc
    except (OSError, paths.PackageAdaptationError) as exc:
        raise BuildWorkspaceError("output_create_failed") from exc


def _write_exclusive(parent: Any, name: str, body: bytes, executable: bool = False) -> None:
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_BINARY", 0)
    mode = 0o700 if executable else 0o600
    try:
        if isinstance(parent, paths._PathDir):
            parent.verify()
            descriptor = os.open(parent.path / name, flags, mode)
        else:
            descriptor = os.open(name, flags, mode, dir_fd=parent)
        try:
            with os.fdopen(descriptor, "wb") as handle:
                descriptor = -1
                handle.write(body)
        finally:
            if descriptor != -1:
                os.close(descriptor)
    except (OSError, paths.PackageAdaptationError) as exc:
        raise BuildWorkspaceError("output_write_failed") from exc


def _copy_target(candidate: Any, inventory: Mapping[str, Any], blobs: Mapping[str, bytes]) -> None:
    opened: dict[str, Any] = {"": candidate}
    try:
        for name in sorted(inventory["directories"], key=lambda item: (item.count("/"), item)):
            parent, _, leaf = name.rpartition("/")
            opened[name] = _make_dir(opened[parent], leaf)
        for row in inventory["files"]:
            parent, _, leaf = row["path"].rpartition("/")
            _write_exclusive(opened[parent], leaf, blobs[row["blobHash"]], row["executable"])
    finally:
        for name in sorted((name for name in opened if name), key=lambda item: item.count("/"), reverse=True):
            paths._dir_close(opened[name])


def _receipt_digest(receipt: Mapping[str, Any]) -> str:
    value = {key: item for key, item in receipt.items() if key != "receiptDigest"}
    return revisions.digest_bytes(revisions.canonical_json(value).encode("utf-8"))


def prepare_build_workspace(target: str | os.PathLike[str], sources: Sequence[str | os.PathLike[str]], staging_dir: str | os.PathLike[str]) -> dict[str, Any]:
    """Capture a target and donors, then exclusively create a private target-only candidate.

    Input 0 is the target; subsequent collision input indexes are source order + 1.
    On failure an already-created private workspace is retained, never deleted.
    """
    if isinstance(sources, (str, bytes, os.PathLike)) or not isinstance(sources, Sequence):
        raise BuildWorkspaceError("invalid_sources")
    if len(sources) > MAX_SOURCES:
        raise BuildWorkspaceError("workspace_source_count_limit")
    roots = [_absolute(target), *(_absolute(source) for source in sources)]
    stage = _absolute(staging_dir)
    for index, root in enumerate(roots):
        if _overlap(root, stage) or any(_overlap(root, other) for other in roots[:index]):
            raise BuildWorkspaceError("path_overlap")
    inventories: list[dict[str, Any]] = []
    target_blobs: dict[str, bytes] = {}
    input_budget = [MAX_INPUT_CAPTURE_BYTES]
    for index, root in enumerate(roots):
        inventory, blobs = _scan(root, input_budget=input_budget)
        inventories.append(inventory)
        if index == 0:
            target_blobs = blobs
    parent = _open_dir(stage.parent)
    stage_handle = None
    candidate_handle = None
    try:
        stage_handle = _make_dir(parent, stage.name)
        candidate_handle = _make_dir(stage_handle, "candidate")
        _copy_target(candidate_handle, inventories[0], target_blobs)
    finally:
        if candidate_handle is not None:
            paths._dir_close(candidate_handle)
        if stage_handle is not None:
            paths._dir_close(stage_handle)
        paths._dir_close(parent)
    candidate, _ = _scan(stage / "candidate")
    if candidate["omittedPaths"] or any(candidate[field] != inventories[0][field] for field in ("treeDigest", "canonicalEntry", "directories")):
        raise BuildWorkspaceError("candidate_copy_mismatch")
    for index, root in enumerate(roots):
        current, _ = _scan(root)
        if current["digest"] != inventories[index]["digest"]:
            raise BuildWorkspaceError("source_changed")
    receipt: dict[str, Any] = {
        "schemaVersion": SCHEMA,
        "status": "prepared",
        "executionPerformed": False,
        "activationAuthorized": False,
        "stagingDir": str(stage),
        "candidateDir": str(stage / "candidate"),
        "inputs": [{"role": "target" if index == 0 else "source", "path": str(root), "inventory": inventories[index]} for index, root in enumerate(roots)],
        "collisions": _collisions(inventories),
        "candidateDigest": candidate["digest"],
        "candidateTreeDigest": candidate["treeDigest"],
        "omissions": dict(_OMISSIONS),
        **_readiness(),
    }
    receipt["receiptDigest"] = _receipt_digest(receipt)
    receipt_bytes = (revisions.canonical_json(receipt) + "\n").encode("utf-8")
    if len(receipt_bytes) > revisions.MAX_TREE_BYTES:
        raise BuildWorkspaceError("receipt_size_limit")
    stage_handle = _open_dir(stage)
    try:
        _write_exclusive(stage_handle, _MANIFEST, receipt_bytes)
    finally:
        paths._dir_close(stage_handle)
    return receipt


def _check_receipt(receipt: Mapping[str, Any]) -> tuple[Path, list[dict[str, Any]]]:
    try:
        if not isinstance(receipt, Mapping) or receipt.get("schemaVersion") != SCHEMA or receipt.get("receiptDigest") != _receipt_digest(receipt):
            raise BuildWorkspaceError("invalid_receipt")
        stage = _absolute(receipt["stagingDir"])
        if str(stage / "candidate") != receipt["candidateDir"]:
            raise BuildWorkspaceError("invalid_receipt")
        roots = receipt["inputs"]
        if not isinstance(roots, list) or not roots or roots[0]["role"] != "target" or any(item["role"] != "source" for item in roots[1:]):
            raise BuildWorkspaceError("invalid_receipt")
        if len(roots) - 1 > MAX_SOURCES:
            raise BuildWorkspaceError("workspace_source_count_limit")
        directory = _open_dir(stage)
        try:
            saved = json.loads(_read_file(directory, _MANIFEST, revisions.MAX_TREE_BYTES).decode("utf-8"))
        finally:
            paths._dir_close(directory)
        if saved != dict(receipt):
            raise BuildWorkspaceError("invalid_receipt")
        return stage, roots
    except (KeyError, TypeError, ValueError) as exc:
        if isinstance(exc, BuildWorkspaceError):
            raise
        raise BuildWorkspaceError("invalid_receipt") from exc


def _validate_contract(name: str, body: bytes) -> None:
    """Validate local, value-free metadata without following card references."""
    from . import package_contract
    from .experience_contracts import ContractValidationError, validate_mcp_policy

    try:
        raw = body.decode("utf-8")
        value = json.loads(raw)
        if not isinstance(value, dict) or package_contract.PLACEHOLDER_RE.search(raw):
            raise ValueError
    except (ValueError, UnicodeDecodeError) as exc:
        raise BuildWorkspaceError("invalid_contract_metadata") from exc

    blocked = {"apikey", "accesskey", "accesstoken", "token", "password", "passwd", "secret", "credentials", "authorization", "headers", "privatekey"}

    def inspect(item: Any) -> None:
        if isinstance(item, dict):
            for key, child in item.items():
                normalized = re.sub(r"[^a-z0-9]", "", str(key).lower())
                if normalized in blocked or (normalized == "env" and name != "mcp-policy.json"):
                    raise BuildWorkspaceError("private_contract_metadata")
                inspect(child)
        elif isinstance(item, list):
            for child in item:
                inspect(child)
        elif isinstance(item, str) and (secret_like_kinds(item) or contains_private_path(item)):
            raise BuildWorkspaceError("private_contract_metadata")

    inspect(value)
    if name == "mcp-policy.json":
        try:
            validate_mcp_policy(value)
        except ContractValidationError as exc:
            raise BuildWorkspaceError("invalid_mcp_policy") from exc
    else:
        schema_name = "agent-card.schema.json" if name == "agent-card.json" else "routing-card.schema.json"
        schema = Path(__file__).parent.parent / "schemas" / schema_name
        if package_contract._schema_shape_errors(value, schema):
            raise BuildWorkspaceError("invalid_contract_metadata")


def _manifest_matches(target: Mapping[str, Any], candidate: Mapping[str, Any]) -> bool:
    def find(inventory: Mapping[str, Any]) -> Mapping[str, Any] | None:
        return next((row for row in inventory["files"] if row["path"].lower() == "agentlas.json"), None)

    original, current = find(target), find(candidate)
    return bool(original and current and original["blobHash"] == current["blobHash"] and original["executable"] == current["executable"])


def _baseline_manifest(target_root: Mapping[str, Any]) -> bytes:
    inventory, blobs = _scan(_absolute(target_root["path"]))
    if inventory["digest"] != target_root["inventory"]["digest"]:
        raise BuildWorkspaceError("source_changed")
    rows = [row for row in inventory["files"] if row["path"] == "agentlas.json"]
    if len(rows) != 1:
        raise BuildWorkspaceError("manifest_permission_parity_unverified")
    return blobs[rows[0]["blobHash"]]


def _skill_changes(target: Mapping[str, Any], candidate: Mapping[str, Any], blobs: Mapping[str, bytes], baseline: bytes) -> dict[str, Any]:
    """Allow only a strictly additive skills value over exact target bytes."""
    old_rows = [row for row in target["files"] if row["path"] == "agentlas.json"]
    new_rows = [row for row in candidate["files"] if row["path"] == "agentlas.json"]
    if (len(old_rows) != 1 or len(new_rows) != 1 or revisions.digest_bytes(baseline) != old_rows[0]["blobHash"]
        or old_rows[0]["executable"] != new_rows[0]["executable"]):
        raise BuildWorkspaceError("manifest_permission_parity_unverified")
    original, old_text, old_start, old_end = _manifest_field(baseline, "skills")
    current, new_text, new_start, new_end = _manifest_field(blobs[new_rows[0]["blobHash"]], "skills")
    if old_text[:old_start] != new_text[:new_start] or old_text[old_end:] != new_text[new_end:]:
        raise BuildWorkspaceError("manifest_permission_parity_unverified")
    old_skills, new_skills = original["skills"], current["skills"]
    if (not isinstance(old_skills, list) or not isinstance(new_skills, list)
        or len(new_skills) < len(old_skills) or new_skills[:len(old_skills)] != old_skills
        or len(new_skills) - len(old_skills) > MAX_ADDED_SKILLS):
        raise BuildWorkspaceError("invalid_added_skills")
    seen: set[str] = set()
    for name in new_skills:
        if not isinstance(name, str) or not name or "/" in name or "\\" in name or name != unicodedata.normalize("NFC", name):
            raise BuildWorkspaceError("invalid_added_skills")
        try:
            revisions.asset_path(f"skills/{name}/SKILL.md")
        except (revisions.RevisionError, UnicodeError) as exc:
            raise BuildWorkspaceError("invalid_added_skills") from exc
        key = name.casefold()
        if key in seen:
            raise BuildWorkspaceError("invalid_added_skills")
        seen.add(key)
    by_path = {row["path"]: row for row in candidate["files"]}
    added = new_skills[len(old_skills):]
    files = []
    for name in added:
        paths_found = [path for path in (f"skills/{name}/SKILL.md", f".agents/skills/{name}/SKILL.md") if path in by_path]
        if not paths_found:
            raise BuildWorkspaceError("added_skill_file_missing")
        bodies = [blobs[by_path[path]["blobHash"]] for path in paths_found]
        if len(set(bodies)) != 1:
            raise BuildWorkspaceError("added_skill_ambiguous")
        try:
            text = bodies[0].decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")
            frontmatter = re.match(r"---\s*\n(.*?)\n---\s*\n", text, re.S)
            if not frontmatter or not text[frontmatter.end():].strip() or re.search(r"\{\{[A-Za-z0-9_]+\}\}", text):
                raise ValueError
            declared = re.search(r"^name:\s*[\"']?([^\"'\n]+)", frontmatter.group(1), re.M)
            description = re.search(r"^description:\s*(.+)", frontmatter.group(1), re.M)
            if (not declared or declared.group(1).strip() != name or not description
                or not description.group(1).strip().strip("\"'")):
                raise ValueError
        except (UnicodeError, ValueError) as exc:
            raise BuildWorkspaceError("added_skill_invalid") from exc
        files.extend({"name": name, "path": path, "blobHash": by_path[path]["blobHash"]} for path in paths_found)
    return {"added": added, "files": files, "semanticQuality": "not_evaluated"}


def _candidate_inventory(stage: Path, target: Mapping[str, Any], *, allow_added_skills: bool = False, baseline_manifest: bytes | None = None) -> tuple[dict[str, Any], bool]:
    if not isinstance(allow_added_skills, bool):
        raise BuildWorkspaceError("invalid_manifest_policy")
    inventory, blobs = _scan(stage / "candidate")
    if allow_added_skills:
        if baseline_manifest is None:
            raise BuildWorkspaceError("manifest_permission_parity_unverified")
        _skill_changes(target, inventory, blobs, baseline_manifest)
    omitted = inventory["omittedPaths"]
    if not omitted:
        return inventory, False
    if omitted != [".agentlas"] or (not allow_added_skills and not _manifest_matches(target, inventory)):
        raise BuildWorkspaceError("candidate_contains_excluded_assets")
    expected = target["contractMetadata"]
    names = {name for name in _RESTORABLE_CONTRACTS if expected[name] is not None}
    if not names:
        raise BuildWorkspaceError("candidate_contains_excluded_assets")
    root = _open_dir(stage / "candidate")
    contract_dir = None
    try:
        contract_dir = paths._open_directory_at(root, ".agentlas")
        with paths._dir_scandir(contract_dir) as entries:
            actual = {entry.name for entry in entries}
        if actual != names:
            raise BuildWorkspaceError("candidate_contains_excluded_assets")
        for name in sorted(names):
            body = _read_file(contract_dir, name)
            if revisions.digest_bytes(body) != expected[name]:
                raise BuildWorkspaceError("candidate_contract_changed")
            _validate_contract(name, body)
    except (OSError, paths.PackageAdaptationError) as exc:
        raise BuildWorkspaceError("candidate_contract_unreadable") from exc
    finally:
        if contract_dir is not None:
            paths._dir_close(contract_dir)
        paths._dir_close(root)
    return inventory, True


def restore_candidate_contracts(receipt: Mapping[str, Any], *, expected_candidate_digest: str, allow_added_skills: bool = False) -> dict[str, Any]:
    """Explicitly restore selected target contract bytes to one inspected candidate.

    This preserves the target manifest and MCP policy; it does not validate
    referenced files or authorize an experiment, registration, or activation.
    """
    stage, roots = _check_receipt(receipt)
    verify_build_workspace(receipt, expected_candidate_digest=expected_candidate_digest, allow_added_skills=allow_added_skills)
    target = roots[0]["inventory"]
    baseline = _baseline_manifest(roots[0]) if allow_added_skills else None
    before, restored = _candidate_inventory(stage, target, allow_added_skills=allow_added_skills, baseline_manifest=baseline)
    if restored:
        raise BuildWorkspaceError("candidate_contracts_already_exist")
    if not allow_added_skills and not _manifest_matches(target, before):
        raise BuildWorkspaceError("manifest_permission_parity_unverified")
    hashes = target["contractMetadata"]
    names = [name for name in _RESTORABLE_CONTRACTS if hashes[name] is not None]
    if not names:
        raise BuildWorkspaceError("no_restorable_contracts")
    original = _open_dir(_absolute(roots[0]["path"]))
    contract_dir = None
    contents: dict[str, bytes] = {}
    try:
        contract_dir = paths._open_directory_at(original, ".agentlas")
        for name in names:
            body = _read_file(contract_dir, name)
            if revisions.digest_bytes(body) != hashes[name]:
                raise BuildWorkspaceError("source_changed")
            _validate_contract(name, body)
            contents[name] = body
    except (OSError, paths.PackageAdaptationError) as exc:
        raise BuildWorkspaceError("source_changed_or_unreadable") from exc
    finally:
        if contract_dir is not None:
            paths._dir_close(contract_dir)
        paths._dir_close(original)
    candidate_dir = _open_dir(stage / "candidate")
    restored_dir = None
    try:
        restored_dir = _make_dir(candidate_dir, ".agentlas")
        for name in names:
            _write_exclusive(restored_dir, name, contents[name])
    finally:
        if restored_dir is not None:
            paths._dir_close(restored_dir)
        paths._dir_close(candidate_dir)
    after, restored = _candidate_inventory(stage, target, allow_added_skills=allow_added_skills, baseline_manifest=baseline)
    if not restored or any(after[field] != before[field] for field in ("treeDigest", "canonicalEntry", "directories", "rootIdentity")):
        raise BuildWorkspaceError("candidate_changed")
    verify_build_workspace(receipt, expected_candidate_digest=after["digest"], allow_added_skills=allow_added_skills)
    result = {"status": "selected_contracts_restored", "candidateDigest": after["digest"], "restoredContracts": names, "manifestIdentical": _manifest_matches(target, after), "mcpPolicyIdentical": "mcp-policy.json" in names, **_readiness(True)}
    if allow_added_skills:
        inventory, blobs = _scan(stage / "candidate")
        if inventory["digest"] != after["digest"]:
            raise BuildWorkspaceError("candidate_changed")
        result["skillChanges"] = _skill_changes(target, inventory, blobs, baseline)
    return result


def _candidate_changes(target: Mapping[str, Any], candidate: Mapping[str, Any]) -> dict[str, Any]:
    """Describe scanned asset metadata only; excluded paths are not compared."""
    before = {row["path"]: row for row in target["files"]}
    after = {row["path"]: row for row in candidate["files"]}
    result: dict[str, Any] = {"scope": "scanned_assets_only", "added": [], "removed": [], "changed": []}
    def detail(row: Mapping[str, Any] | None) -> dict[str, Any] | None:
        return None if row is None else {"blobHash": row["blobHash"], "executable": row["executable"]}
    for path in sorted(before.keys() | after.keys(), key=lambda value: value.encode("utf-8")):
        old, new = detail(before.get(path)), detail(after.get(path))
        if old == new:
            continue
        kind = "added" if old is None else "removed" if new is None else "changed"
        result[kind].append({"path": path, "before": old, "after": new})
    return result


def inspect_build_candidate(receipt: Mapping[str, Any], *, allow_added_skills: bool = False) -> dict[str, Any]:
    """Return the current candidate inventory and digest for human/host review."""
    stage, roots = _check_receipt(receipt)
    baseline = _baseline_manifest(roots[0]) if allow_added_skills else None
    inventory, restored = _candidate_inventory(stage, roots[0]["inventory"], allow_added_skills=allow_added_skills, baseline_manifest=baseline)
    result = {"status": "unreviewed", "candidateDigest": inventory["digest"], "inventory": inventory, "changes": _candidate_changes(roots[0]["inventory"], inventory), "selectedContractsRestored": restored, **_readiness(restored)}
    if allow_added_skills:
        observed, blobs = _scan(stage / "candidate")
        if observed["digest"] != inventory["digest"]:
            raise BuildWorkspaceError("candidate_changed")
        result["skillChanges"] = _skill_changes(roots[0]["inventory"], observed, blobs, baseline)
    return result


def verify_build_workspace(receipt: Mapping[str, Any], *, expected_candidate_digest: str | None = None, allow_added_skills: bool = False) -> dict[str, Any]:
    """Check all captured source fingerprints and an explicitly expected candidate.

    No semantic review, approval, registration, activation, or publication occurs.
    Passing a new digest binds verification to a separately inspected candidate.
    """
    stage, roots = _check_receipt(receipt)
    baseline = None
    input_budget = [MAX_INPUT_CAPTURE_BYTES]
    for index, item in enumerate(roots):
        current, blobs = _scan(_absolute(item["path"]), input_budget=input_budget)
        if current["digest"] != item["inventory"]["digest"]:
            raise BuildWorkspaceError("source_changed")
        if index == 0 and allow_added_skills:
            rows = [row for row in current["files"] if row["path"] == "agentlas.json"]
            if len(rows) != 1:
                raise BuildWorkspaceError("manifest_permission_parity_unverified")
            baseline = blobs[rows[0]["blobHash"]]
    candidate, restored = _candidate_inventory(stage, roots[0]["inventory"], allow_added_skills=allow_added_skills, baseline_manifest=baseline)
    expected = receipt["candidateDigest"] if expected_candidate_digest is None else expected_candidate_digest
    if not isinstance(expected, str) or not re.fullmatch(r"[0-9a-f]{64}", expected) or candidate["digest"] != expected:
        raise BuildWorkspaceError("candidate_changed")
    return {"status": "verified", "verificationScope": "snapshot_integrity_only", "candidateDigest": candidate["digest"], "inputCount": len(roots), "sourceCount": len(roots) - 1, "selectedContractsRestored": restored, "semanticReview": "not_evaluated", "activationAuthorized": False, "omissions": dict(_OMISSIONS), **_readiness(restored)}


def _manifest_field(body: bytes, field: str) -> tuple[dict[str, Any], str, int, int]:
    """Strictly parse JSON and find exactly one top-level field value span."""
    def unique_pairs(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, item in pairs:
            if key in result:
                raise ValueError("duplicate key")
            result[key] = item
        return result

    def reject_constant(_: str) -> None:
        raise ValueError("nonfinite number")

    def finite_float(raw: str) -> float:
        parsed = float(raw)
        if not math.isfinite(parsed):
            raise ValueError("nonfinite number")
        return parsed

    decoder = json.JSONDecoder(object_pairs_hook=unique_pairs, parse_constant=reject_constant, parse_float=finite_float)
    try:
        text = body.decode("utf-8")
        manifest = decoder.decode(text)
        if not isinstance(manifest, dict) or field not in manifest:
            raise ValueError("missing field")

        def space(index: int) -> int:
            while index < len(text) and text[index] in " \t\r\n":
                index += 1
            return index

        index = space(0)
        if index >= len(text) or text[index] != "{":
            raise ValueError("not an object")
        index = space(index + 1)
        result: tuple[int, int] | None = None
        while index < len(text) and text[index] != "}":
            key, index = decoder.raw_decode(text, index)
            if not isinstance(key, str):
                raise ValueError("invalid key")
            index = space(index)
            if index >= len(text) or text[index] != ":":
                raise ValueError("invalid object")
            start = space(index + 1)
            _, end = decoder.raw_decode(text, start)
            if key == field:
                result = (start, end)
            index = space(end)
            if index < len(text) and text[index] == ",":
                index = space(index + 1)
            elif index >= len(text) or text[index] != "}":
                raise ValueError("invalid object")
        if result is None:
            raise ValueError("missing field")
        return manifest, text, result[0], result[1]
    except (UnicodeError, ValueError, RecursionError) as exc:
        raise BuildWorkspaceError("invalid_snapshot_manifest") from exc


def _replace_manifest_hash(body: bytes, value: str) -> bytes:
    """Replace only the top-level hash token, preserving every other byte."""
    manifest, text, start, end = _manifest_field(body, "packageHash")
    old = manifest.get("packageHash")
    if (not isinstance(old, str) or not re.fullmatch(r"sha256:[0-9a-f]{64}", old)
        or not isinstance(value, str) or not re.fullmatch(r"sha256:[0-9a-f]{64}", value)):
        raise BuildWorkspaceError("invalid_snapshot_manifest")
    return (text[:start] + json.dumps(value) + text[end:]).encode("utf-8")


def _restored_contract_bytes(root_path: Path, target: Mapping[str, Any]) -> dict[str, bytes]:
    """Read only the validated, exactly enumerated target contract subset."""
    expected = target["contractMetadata"]
    names = {name for name in _RESTORABLE_CONTRACTS if expected[name] is not None}
    if not names:
        raise BuildWorkspaceError("no_restorable_contracts")
    root = _open_dir(root_path)
    contract_dir = None
    try:
        contract_dir = paths._open_directory_at(root, ".agentlas")
        with paths._dir_scandir(contract_dir) as entries:
            actual = {entry.name for entry in entries}
        if actual != names:
            raise BuildWorkspaceError("candidate_contains_excluded_assets")
        result: dict[str, bytes] = {}
        for name in sorted(names):
            body = _read_file(contract_dir, name)
            if revisions.digest_bytes(body) != expected[name]:
                raise BuildWorkspaceError("candidate_contract_changed")
            _validate_contract(name, body)
            result[name] = body
        return result
    except (OSError, paths.PackageAdaptationError) as exc:
        raise BuildWorkspaceError("candidate_contract_unreadable") from exc
    finally:
        if contract_dir is not None:
            paths._dir_close(contract_dir)
        paths._dir_close(root)


def _runtime_hash_from_capture(inventory: Mapping[str, Any], blobs: Mapping[str, bytes], contracts: Mapping[str, bytes]) -> str:
    """Mirror runtime's text collection using already bounded, checked bytes."""
    from .runtime import PACKAGE_HASH_VERSION, PackageFile, TEXT_FILE_ALLOW, is_local_experience_lineage_path, package_hash

    if PACKAGE_HASH_VERSION != _SNAPSHOT_HASH_CONTRACT["algorithm"]:
        raise BuildWorkspaceError("unsupported_runtime_hash_version")

    captured = [(row["path"], blobs[row["blobHash"]]) for row in inventory["files"]]
    captured.extend((f".agentlas/{name}", body) for name, body in contracts.items())
    files: list[PackageFile] = []
    for relative, body in captured:
        if (is_local_experience_lineage_path(relative) or relative.startswith(".git/")
            or "/node_modules/" in f"/{relative}/" or relative.startswith("node_modules/")):
            continue
        suffix = Path(relative).suffix
        if suffix and suffix not in TEXT_FILE_ALLOW:
            continue
        try:
            # Path.read_text() uses universal-newline conversion on every host.
            content = body.decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")
        except UnicodeDecodeError:
            continue
        files.append(PackageFile(path=relative, content=content))
    return package_hash(files)


def _snapshot_mode_digest(root_path: Path, inventory: Mapping[str, Any], contract_names: Sequence[str]) -> str:
    """Capture full local mode bits as well as the executable-bit tree digest."""
    root = _open_dir(root_path)
    opened: dict[str, Any] = {"": root}
    rows: list[dict[str, Any]] = []
    try:
        directories = sorted([*inventory["directories"], ".agentlas"], key=lambda name: (name.count("/"), name))
        for relative in directories:
            parent, _, leaf = relative.rpartition("/")
            opened[relative] = paths._open_directory_at(opened[parent], leaf)
        for relative in ["", *directories]:
            handle = opened[relative]
            if isinstance(handle, paths._PathDir):
                handle.verify()
                info = os.lstat(handle.path)
            else:
                info = os.fstat(handle)
            if paths._is_link_like(info) or not stat.S_ISDIR(info.st_mode):
                raise BuildWorkspaceError("snapshot_changed")
            mode = stat.S_IMODE(info.st_mode)
            if os.name != "nt" and mode & 0o7077:
                raise BuildWorkspaceError("snapshot_insecure_permissions")
            rows.append({"path": relative, "kind": "directory", "mode": mode, "uid": info.st_uid, "gid": info.st_gid})
        filenames = [row["path"] for row in inventory["files"]]
        filenames.extend(f".agentlas/{name}" for name in contract_names)
        for relative in sorted(filenames):
            parent, _, leaf = relative.rpartition("/")
            info = paths._dir_entry_lstat(opened[parent], leaf)
            if paths._is_link_like(info) or not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
                raise BuildWorkspaceError("snapshot_changed")
            mode = stat.S_IMODE(info.st_mode)
            if os.name != "nt" and mode & 0o7077:
                raise BuildWorkspaceError("snapshot_insecure_permissions")
            rows.append({"path": relative, "kind": "file", "mode": mode, "uid": info.st_uid, "gid": info.st_gid})
        return revisions.digest_bytes(revisions.canonical_json(rows).encode("utf-8"))
    except (OSError, paths.PackageAdaptationError, KeyError) as exc:
        raise BuildWorkspaceError("snapshot_changed") from exc
    finally:
        for name in sorted((name for name in opened if name), key=lambda item: item.count("/"), reverse=True):
            paths._dir_close(opened[name])
        paths._dir_close(root)


def _capture_restored_candidate(stage: Path, target: Mapping[str, Any], expected_digest: str, *, allow_added_skills: bool = False, baseline_manifest: bytes | None = None) -> tuple[dict[str, Any], dict[str, bytes], dict[str, bytes]]:
    before, restored = _candidate_inventory(stage, target, allow_added_skills=allow_added_skills, baseline_manifest=baseline_manifest)
    if not restored:
        raise BuildWorkspaceError("candidate_contract_metadata_not_restored")
    if before["digest"] != expected_digest:
        raise BuildWorkspaceError("candidate_changed")
    inventory, blobs = _scan(stage / "candidate")
    if inventory["digest"] != expected_digest:
        raise BuildWorkspaceError("candidate_changed")
    contracts = _restored_contract_bytes(stage / "candidate", target)
    after, restored = _candidate_inventory(stage, target, allow_added_skills=allow_added_skills, baseline_manifest=baseline_manifest)
    if not restored or after["digest"] != expected_digest:
        raise BuildWorkspaceError("candidate_changed")
    return inventory, blobs, contracts


def _snapshot_expected(candidate: Mapping[str, Any], blobs: Mapping[str, bytes], package_hash: str) -> tuple[list[dict[str, Any]], dict[str, bytes]]:
    rows = [dict(row) for row in candidate["files"]]
    manifests = [row for row in rows if row["path"] == "agentlas.json"]
    if len(manifests) != 1:
        raise BuildWorkspaceError("invalid_snapshot_manifest")
    manifest = manifests[0]
    body = _replace_manifest_hash(blobs[manifest["blobHash"]], package_hash)
    digest = revisions.digest_bytes(body)
    manifest.update({"blobHash": digest, "byteLength": len(body)})
    result = dict(blobs)
    result[digest] = body
    return rows, result


def _snapshot_content(package_dir: Path, target: Mapping[str, Any], candidate: Mapping[str, Any], candidate_blobs: Mapping[str, bytes], candidate_contracts: Mapping[str, bytes]) -> tuple[dict[str, Any], str, str]:
    package_hash = _runtime_hash_from_capture(candidate, candidate_blobs, candidate_contracts)
    expected_rows, _ = _snapshot_expected(candidate, candidate_blobs, package_hash)
    inventory, blobs = _scan(package_dir)
    if inventory["omittedPaths"] != [".agentlas"]:
        raise BuildWorkspaceError("snapshot_changed")
    contracts = _restored_contract_bytes(package_dir, target)
    if contracts != candidate_contracts:
        raise BuildWorkspaceError("snapshot_changed")
    if (inventory["files"] != revisions.tree_payload(expected_rows)["files"]
        or inventory["directories"] != candidate["directories"]
        or inventory["canonicalEntry"] != candidate["canonicalEntry"]
        or _runtime_hash_from_capture(inventory, blobs, contracts) != package_hash):
        raise BuildWorkspaceError("snapshot_changed")
    modes = _snapshot_mode_digest(package_dir, inventory, sorted(contracts))
    # A second content/contract check brackets the mode scan. These checks are
    # observations, not a lock against a non-cooperating concurrent writer.
    after, _ = _scan(package_dir)
    if after["digest"] != inventory["digest"] or _restored_contract_bytes(package_dir, target) != contracts:
        raise BuildWorkspaceError("snapshot_changed")
    if _snapshot_mode_digest(package_dir, after, sorted(contracts)) != modes:
        raise BuildWorkspaceError("snapshot_changed")
    return inventory, modes, package_hash


def _boundary_state(stage: Path, snapshot_id: str | None = None) -> dict[str, Any]:
    """Check owned stage/receipt and optional snapshot directory/receipt modes."""
    stage_handle = _open_dir(stage)
    snapshot_handle = None
    try:
        def directory_info(handle: Any) -> os.stat_result:
            if isinstance(handle, paths._PathDir):
                handle.verify()
                return os.lstat(handle.path)
            return os.fstat(handle)

        def check(info: os.stat_result, *, directory: bool) -> dict[str, int]:
            if (paths._is_link_like(info) or (not stat.S_ISDIR(info.st_mode) if directory else not stat.S_ISREG(info.st_mode))
                or (not directory and info.st_nlink != 1)):
                raise BuildWorkspaceError("workspace_unsafe_boundary")
            if os.name != "nt":
                if hasattr(os, "geteuid") and info.st_uid != os.geteuid():
                    raise BuildWorkspaceError("workspace_owner_mismatch")
                if stat.S_IMODE(info.st_mode) & 0o7077:
                    raise BuildWorkspaceError("workspace_insecure_permissions")
            return {"device": info.st_dev, "inode": info.st_ino, "mode": stat.S_IMODE(info.st_mode), "uid": info.st_uid, "gid": info.st_gid}

        state: dict[str, Any] = {
            "stage": check(directory_info(stage_handle), directory=True),
            "workspaceReceipt": check(paths._dir_entry_lstat(stage_handle, _MANIFEST), directory=False),
        }
        if snapshot_id is not None:
            snapshot_handle = paths._open_directory_at(stage_handle, snapshot_id)
            state["snapshotDir"] = check(directory_info(snapshot_handle), directory=True)
            state["snapshotReceipt"] = check(paths._dir_entry_lstat(snapshot_handle, "snapshot.json"), directory=False)
        return state
    except (OSError, paths.PackageAdaptationError) as exc:
        raise BuildWorkspaceError("workspace_unsafe_boundary") from exc
    finally:
        if snapshot_handle is not None:
            paths._dir_close(snapshot_handle)
        paths._dir_close(stage_handle)


def _boundary_digest(state: Mapping[str, Any]) -> str:
    return revisions.digest_bytes(revisions.canonical_json(state).encode("utf-8"))


def _write_empty_receipt(parent: Any, body: bytes, expected: Mapping[str, int]) -> None:
    """Fill a just-created empty receipt while checking the opened identity."""
    flags = os.O_WRONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_BINARY", 0)
    descriptor = None
    try:
        if isinstance(parent, paths._PathDir):
            parent.verify()
            descriptor = os.open(parent.path / "snapshot.json", flags)
        else:
            descriptor = os.open("snapshot.json", flags, dir_fd=parent)
        info = os.fstat(descriptor)
        actual = {"device": info.st_dev, "inode": info.st_ino, "mode": stat.S_IMODE(info.st_mode), "uid": info.st_uid, "gid": info.st_gid}
        if actual != expected or info.st_size != 0 or not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
            raise BuildWorkspaceError("workspace_unsafe_boundary")
        remaining = memoryview(body)
        while remaining:
            count = os.write(descriptor, remaining)
            if count <= 0:
                raise BuildWorkspaceError("output_write_failed")
            remaining = remaining[count:]
        after = os.fstat(descriptor)
        if (after.st_dev, after.st_ino, stat.S_IMODE(after.st_mode), after.st_uid, after.st_gid, after.st_size) != (
            expected["device"], expected["inode"], expected["mode"], expected["uid"], expected["gid"], len(body)):
            raise BuildWorkspaceError("workspace_unsafe_boundary")
    except (OSError, paths.PackageAdaptationError) as exc:
        raise BuildWorkspaceError("output_write_failed") from exc
    finally:
        if descriptor is not None:
            os.close(descriptor)


def _snapshot_digest(snapshot_id: str, workspace_digest: str, candidate_digest: str, inventory: Mapping[str, Any], modes: str, package_hash: str, boundary_digest: str | None = None) -> str:
    payload = {
        "schemaVersion": SNAPSHOT_SCHEMA,
        "snapshotId": snapshot_id,
        "workspaceReceiptDigest": workspace_digest,
        "candidateDigest": candidate_digest,
        "inventoryDigest": inventory["digest"],
        "modeDigest": modes,
        "runtimePackageHash": package_hash,
    }
    # Absent for early v1 snapshots; new snapshots bind boundary identities and
    # permission bits without changing or invalidating workspace v1 receipts.
    if boundary_digest is not None:
        payload["boundaryDigest"] = boundary_digest
    return revisions.digest_bytes(revisions.canonical_json(payload).encode("utf-8"))


def create_experiment_snapshot(receipt: Mapping[str, Any], *, expected_candidate_digest: str, allow_added_skills: bool = False) -> dict[str, Any]:
    """Exclusively create a non-activating snapshot from a restored candidate.

    The source, candidate and saved workspace receipt are verified before and
    after copying. Only the candidate manifest's hash token changes. Partial
    private output may remain after failure; after a creation attempt the raised
    BuildWorkspaceError has ``partial_snapshot_id``. Existence or ownership of
    that path must be verified separately before any cleanup.
    Verification is point-in-time and does not lock out non-cooperating writers.
    """
    stage, roots = _check_receipt(receipt)
    initial_boundary = _boundary_state(stage)
    verify_build_workspace(receipt, expected_candidate_digest=expected_candidate_digest, allow_added_skills=allow_added_skills)
    target = roots[0]["inventory"]
    baseline = _baseline_manifest(roots[0]) if allow_added_skills else None
    candidate, blobs, contracts = _capture_restored_candidate(stage, target, expected_candidate_digest, allow_added_skills=allow_added_skills, baseline_manifest=baseline)
    changes = _skill_changes(target, candidate, blobs, baseline) if allow_added_skills else None
    package_hash = _runtime_hash_from_capture(candidate, blobs, contracts)
    rows, snapshot_blobs = _snapshot_expected(candidate, blobs, package_hash)
    snapshot_id = f"experiment-{uuid.uuid4().hex}"
    snapshot_dir = stage / snapshot_id
    package_dir = snapshot_dir / "package"
    stage_handle = _open_dir(stage)
    snapshot_handle = None
    package_handle = None
    creation_attempted = False
    try:
        creation_attempted = True
        snapshot_handle = _make_dir(stage_handle, snapshot_id)
        package_handle = _make_dir(snapshot_handle, "package")
        _copy_target(package_handle, {"directories": candidate["directories"], "files": rows}, snapshot_blobs)
        contract_dir = _make_dir(package_handle, ".agentlas")
        try:
            for name in sorted(contracts):
                _write_exclusive(contract_dir, name, contracts[name])
        finally:
            paths._dir_close(contract_dir)
        paths._dir_close(package_handle)
        package_handle = None
        verify_build_workspace(receipt, expected_candidate_digest=expected_candidate_digest, allow_added_skills=allow_added_skills)
        inventory, modes, actual_hash = _snapshot_content(package_dir, target, candidate, blobs, contracts)
        if actual_hash != package_hash:
            raise BuildWorkspaceError("snapshot_changed")
        _write_exclusive(snapshot_handle, "snapshot.json", b"")
        boundary = _boundary_state(stage, snapshot_id)
        if {key: boundary[key] for key in initial_boundary} != initial_boundary:
            raise BuildWorkspaceError("workspace_unsafe_boundary")
        boundary_digest = _boundary_digest(boundary)
        snapshot_digest = _snapshot_digest(snapshot_id, receipt["receiptDigest"], expected_candidate_digest, inventory, modes, package_hash, boundary_digest)
        result: dict[str, Any] = {
            "schemaVersion": SNAPSHOT_SCHEMA,
            "status": "created",
            "snapshotId": snapshot_id,
            "snapshotDir": str(snapshot_dir),
            "packageDir": str(package_dir),
            "workspaceReceiptDigest": receipt["receiptDigest"],
            "candidateDigest": expected_candidate_digest,
            "snapshotDigest": snapshot_digest,
            "boundaryDigest": boundary_digest,
            "runtimePackageHash": package_hash,
            "hashContract": dict(_SNAPSHOT_HASH_CONTRACT),
            "contractFiles": sorted(contracts),
            "manifestPolicy": "additive_skills" if allow_added_skills else "strict_identical",
            "manifestPreservation": "candidate_bytes_except_packageHash_and_target_bytes_except_skills_and_packageHash" if allow_added_skills else "all_original_bytes_except_packageHash_value",
            "unscannedBinaryPaths": inventory["unscannedBinaryPaths"],
            "verificationScope": "point_in_time_snapshot_only",
            "concurrencyLimitation": "No lock prevents non-cooperating writers; verify immediately before consumption and protect the captured package.",
            "permissionLimitation": "Stage and snapshot owner/mode bits are checked on POSIX; ancestor directories, ACLs and Windows permissions are not verified.",
            "partialOutputCleanup": "Not automatic; a failed exclusive snapshot may remain in the private workspace.",
            "semanticReview": "not_evaluated",
            "runtimeBundleValidation": "not_performed",
            "executionPerformed": False,
            "activationAuthorized": False,
            **_readiness(True),
        }
        if changes is not None:
            result["skillChanges"] = changes
        result["receiptDigest"] = _receipt_digest(result)
        _write_empty_receipt(snapshot_handle, (revisions.canonical_json(result) + "\n").encode("utf-8"), boundary["snapshotReceipt"])
        if _boundary_state(stage, snapshot_id) != boundary:
            raise BuildWorkspaceError("workspace_unsafe_boundary")
    except Exception as exc:
        if creation_attempted:
            if isinstance(exc, BuildWorkspaceError):
                exc.partial_snapshot_id = snapshot_id
            else:
                error = BuildWorkspaceError("snapshot_partial_create")
                error.partial_snapshot_id = snapshot_id
                raise error from exc
        raise
    finally:
        if package_handle is not None:
            paths._dir_close(package_handle)
        if snapshot_handle is not None:
            paths._dir_close(snapshot_handle)
        paths._dir_close(stage_handle)
    try:
        verify_experiment_snapshot(receipt, result, expected_snapshot_digest=snapshot_digest, allow_added_skills=allow_added_skills)
    except BuildWorkspaceError as exc:
        exc.partial_snapshot_id = snapshot_id
        raise
    return result


def verify_experiment_snapshot(receipt: Mapping[str, Any], snapshot_receipt: Mapping[str, Any], *, expected_snapshot_digest: str, allow_added_skills: bool = False) -> dict[str, Any]:
    """Recheck workspace, final package and the caller-held snapshot digest.

    The caller must retain the expected digest from creation independently of
    the mutable on-disk receipt. No host execution or approval is implied.
    """
    stage, roots = _check_receipt(receipt)
    if (not isinstance(snapshot_receipt, Mapping) or snapshot_receipt.get("schemaVersion") != SNAPSHOT_SCHEMA
        or snapshot_receipt.get("receiptDigest") != _receipt_digest(snapshot_receipt)
        or snapshot_receipt.get("workspaceReceiptDigest") != receipt["receiptDigest"]):
        raise BuildWorkspaceError("invalid_snapshot_receipt")
    if not isinstance(allow_added_skills, bool):
        raise BuildWorkspaceError("invalid_manifest_policy")
    policy = snapshot_receipt.get("manifestPolicy", "strict_identical")
    if policy not in {"strict_identical", "additive_skills"}:
        raise BuildWorkspaceError("invalid_snapshot_receipt")
    if policy == "additive_skills" and not allow_added_skills:
        raise BuildWorkspaceError("added_skills_opt_in_required")
    effective_skills = policy == "additive_skills"
    snapshot_id = snapshot_receipt.get("snapshotId")
    if not isinstance(snapshot_id, str) or not re.fullmatch(r"experiment-[0-9a-f]{32}", snapshot_id):
        raise BuildWorkspaceError("invalid_snapshot_receipt")
    snapshot_dir = stage / snapshot_id
    package_dir = snapshot_dir / "package"
    if snapshot_receipt.get("snapshotDir") != str(snapshot_dir) or snapshot_receipt.get("packageDir") != str(package_dir):
        raise BuildWorkspaceError("invalid_snapshot_receipt")
    if (not isinstance(expected_snapshot_digest, str) or not re.fullmatch(r"[0-9a-f]{64}", expected_snapshot_digest)
        or snapshot_receipt.get("snapshotDigest") != expected_snapshot_digest):
        raise BuildWorkspaceError("snapshot_changed")
    boundary = _boundary_state(stage, snapshot_id)
    boundary_digest = snapshot_receipt.get("boundaryDigest")
    if boundary_digest is not None and boundary_digest != _boundary_digest(boundary):
        raise BuildWorkspaceError("workspace_unsafe_boundary")
    directory = _open_dir(snapshot_dir)
    try:
        try:
            saved = json.loads(_read_file(directory, "snapshot.json", revisions.MAX_TREE_BYTES).decode("utf-8"))
        except (ValueError, UnicodeError, RecursionError) as exc:
            raise BuildWorkspaceError("invalid_snapshot_receipt") from exc
    finally:
        paths._dir_close(directory)
    if saved != dict(snapshot_receipt):
        raise BuildWorkspaceError("invalid_snapshot_receipt")
    candidate_digest = snapshot_receipt.get("candidateDigest")
    verify_build_workspace(receipt, expected_candidate_digest=candidate_digest, allow_added_skills=effective_skills)
    target = roots[0]["inventory"]
    baseline = _baseline_manifest(roots[0]) if effective_skills else None
    candidate, blobs, contracts = _capture_restored_candidate(stage, target, candidate_digest, allow_added_skills=effective_skills, baseline_manifest=baseline)
    changes = _skill_changes(target, candidate, blobs, baseline) if effective_skills else None
    inventory, modes, package_hash = _snapshot_content(package_dir, target, candidate, blobs, contracts)
    actual = _snapshot_digest(snapshot_id, receipt["receiptDigest"], candidate_digest, inventory, modes, package_hash, boundary_digest)
    if (actual != expected_snapshot_digest or package_hash != snapshot_receipt.get("runtimePackageHash")
        or sorted(contracts) != snapshot_receipt.get("contractFiles")
        or (effective_skills and changes != snapshot_receipt.get("skillChanges"))
        or inventory["unscannedBinaryPaths"] != snapshot_receipt.get("unscannedBinaryPaths")):
        raise BuildWorkspaceError("snapshot_changed")
    verify_build_workspace(receipt, expected_candidate_digest=candidate_digest, allow_added_skills=effective_skills)
    if _boundary_state(stage, snapshot_id) != boundary:
        raise BuildWorkspaceError("workspace_unsafe_boundary")
    result = {"status": "verified", "snapshotDigest": actual, "runtimePackageHash": package_hash,
            "hashContract": dict(_SNAPSHOT_HASH_CONTRACT),
            "permissionLimitation": "Stage and snapshot owner/mode bits are checked on POSIX; ancestor directories, ACLs and Windows permissions are not verified.",
            "verificationScope": "point_in_time_snapshot_only", "executionPerformed": False,
            "activationAuthorized": False, "semanticReview": "not_evaluated",
            "runtimeBundleValidation": "not_performed", **_readiness(True)}
    if changes is not None:
        result["skillChanges"] = changes
    return result
